def assert_no_customer_contact(raw: str, example: dict[str, object]) -> None:
    phone = example["phone"]
    phone_digits = example["phone_digits"]
    email = example["email"]
    full_name = example["full_name"]
    assert isinstance(phone, str)
    assert isinstance(phone_digits, str)
    assert isinstance(email, str)
    assert isinstance(full_name, str)
    assert phone not in raw
    assert phone_digits not in raw
    assert email not in raw
    assert "@" not in raw
    assert full_name not in raw
